#!/usr/bin/env python3
"""Generates app/src/io/freemytv/Tokens.java from design/tokens.json.

    python3 tools/tokens.py           # write Tokens.java
    python3 tools/tokens.py --check   # fail if the committed file drifted

Sizes are px on the 1920×1080 stage. Callers multiply by the screen scale.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "design", "tokens.json")
OUT = os.path.join(ROOT, "app", "src", "io", "freemytv", "Tokens.java")


def argb(value):
    value = value.strip()
    if value.startswith("#"):
        h = value[1:]
        if len(h) == 6:
            return 0xFF000000 | int(h, 16)
        if len(h) == 8:
            return int(h, 16)
        raise ValueError(value)
    m = re.match(r"rgba\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*\)", value)
    if not m:
        raise ValueError(value)
    r, g, b = (int(float(m.group(i))) for i in (1, 2, 3))
    a = int(round(float(m.group(4)) * 255))
    return (a << 24) | (r << 16) | (g << 8) | b


def const_name(key):
    return re.sub(r"[^A-Za-z0-9]+", "_", key).upper()


def java(tokens):
    lines = []
    w = lines.append
    w("package io.freemytv;")
    w("")
    w("/**")
    w(" * Design tokens from design/tokens.json, generated by tools/tokens.py. Do not edit.")
    w(" * Colours are ARGB. Sizes are px at 1920×1080; screens multiply by their scale.")
    w(" */")
    w("final class Tokens {")
    w("    private Tokens() {}")
    w("")
    colors = tokens["color"]
    themes = ("light", "dark")
    keys = list(colors["light"].keys())
    for key in keys:
        name = const_name(key)
        for theme in themes:
            w("    static final int %s_%s = 0x%08X;" % (name, theme.upper(), argb(colors[theme][key]) & 0xFFFFFFFF))
        w("")
        method = re.sub(r"[^A-Za-z0-9]+", " ", key).title().replace(" ", "")
        method = method[0].lower() + method[1:]
        w("    static int %s(boolean dark) { return dark ? %s_DARK : %s_LIGHT; }" % (method, name, name))
        w("")
    accent = colors["accent"]
    for key, value in accent.items():
        w("    static final int ACCENT_%s = 0x%08X;" % (const_name(key), argb(value) & 0xFFFFFFFF))
    scrim = colors["scrim.pop"]
    scrim_plain = colors["scrim.popNoBlur"]
    w("    /** Pop-out scrim where RenderEffect blur is available (Android 12+). */")
    w("    static final float SCRIM_POP = %.2ff;" % alpha_of(scrim))
    w("    /** Pop-out scrim where blur is not (Android 8 to 11). tokens.json, not the HTML mock's 0.76. */")
    w("    static final float SCRIM_POP_NO_BLUR = %.2ff;" % alpha_of(scrim_plain))
    w("")
    type_ = tokens["type"]
    for role, spec in type_.items():
        if not isinstance(spec, dict) or "size" not in spec:
            continue
        name = const_name(role)
        w("    static final float TYPE_%s = %sf;" % (name, spec["size"]))
        w("    static final int WEIGHT_%s = %s;" % (name, spec["weight"]))
    w("")
    space = tokens["space"]
    for key, value in space.items():
        if key == "unit":
            continue
        w("    static final float SPACE_%s = %sf;" % (const_name(key), value))
    w("")
    for key, value in tokens["radius"].items():
        w("    static final float RADIUS_%s = %sf;" % (const_name(key), value))
    w("")
    for key, value in tokens["card"].items():
        w("    static final float CARD_%s = %sf;" % (const_name(key), value))
    w("")
    focus = tokens["focus"]
    w("    static final float FOCUS_CARD = %sf;" % focus["scale.card"])
    w("    static final float FOCUS_TILE = %sf;" % focus["scale.tile"])
    w("    static final float FOCUS_KEY = %sf;" % focus["scale.key"])
    w("    static final float FOCUS_LIFT = %sf;" % focus["lift"])
    w("    static final float FOCUS_RING = %sf;" % focus["ring"])
    w("")
    motion = tokens["motion"]
    w("    static final int MOTION_FOCUS_MS = %s;" % motion["focus"]["ms"])
    w("    static final int MOTION_POP_MS = %s;" % motion["pop"]["ms"])
    w("    static final int MOTION_FADE_MS = %s;" % motion["fade"]["ms"])
    w("    static final int MOTION_TRAILER_REST_MS = %s;" % motion["rest.trailer"])
    ease = motion["pop"]["ease"]
    nums = re.findall(r"\d*\.?\d+", ease[ease.find("("):])
    w("    static final float POP_X1 = %sf, POP_Y1 = %sf, POP_X2 = %sf, POP_Y2 = %sf;" % tuple(nums[:4]))
    w("")
    for key, value in tokens["layout"].items():
        w("    static final float LAYOUT_%s = %sf;" % (const_name(key), value))
    w("}")
    w("")
    return "\n".join(lines)


def alpha_of(value):
    m = re.search(r"([\d.]+)\s*\)\s*$", value.strip())
    return float(m.group(1))


def main():
    with open(SRC, encoding="utf-8") as f:
        text = java(json.load(f))
    check = "--check" in sys.argv
    if check:
        with open(OUT, encoding="utf-8") as f:
            have = f.read()
        if have != text:
            sys.stderr.write("Tokens.java does not match design/tokens.json. Run python3 tools/tokens.py\n")
            sys.exit(1)
        print("Tokens.java matches design/tokens.json.")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("Wrote " + os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
